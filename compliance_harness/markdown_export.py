from __future__ import annotations

from datetime import date
from pathlib import Path

from compliance_harness.config import HarnessConfig, SEVERITY_ORDER
from compliance_harness.db import ComplianceDB


def write_session_report(config: HarnessConfig, session_id: str) -> Path:
    db = ComplianceDB(config.sqlite_path)
    data = db.get_session_data(session_id)
    session = data.get("session", {})

    md_dir = config.markdown_dir / "sessions"
    md_dir.mkdir(parents=True, exist_ok=True)

    started = session.get("started_at", "unknown")[:19].replace(":", "-")
    path = md_dir / f"session-{started}-{session_id[:8]}.md"
    path.write_text(_render_session_markdown(config, data))
    return path


def write_daily_report(config: HarnessConfig, day: date | None = None) -> Path:
    db = ComplianceDB(config.sqlite_path)
    day = day or date.today()
    date_str = day.isoformat()
    data = db.get_daily_data(date_str, config.project_name)

    md_dir = config.markdown_dir / "daily"
    md_dir.mkdir(parents=True, exist_ok=True)
    path = md_dir / f"{date_str}.md"
    path.write_text(_render_daily_markdown(config, data, date_str))
    return path


def _render_session_markdown(config: HarnessConfig, data: dict) -> str:
    session = data.get("session", {})
    decisions = data.get("decisions", [])
    reviews = data.get("reviews", [])
    findings = data.get("findings", [])

    lines = [
        f"# Compliance Session Report — {config.project_name}",
        "",
        f"**Session ID:** `{session.get('id', '')}`",
        f"**Started:** {session.get('started_at', '')}",
        f"**Branch:** {session.get('git_branch', 'n/a')}",
        f"**HEAD:** {session.get('git_head', 'n/a')}",
        "",
        "## Summary",
        "",
        f"- Reviews: {len(reviews)}",
        f"- Decisions: {len(decisions)}",
        f"- Findings: {len(findings)}",
        "",
    ]

    if findings:
        lines.extend(["## Findings", ""])
        for f in sorted(findings, key=lambda x: SEVERITY_ORDER.get(x["severity"], 0), reverse=True):
            lines.extend([
                f"### [{f['severity'].upper()}] {f['title']}",
                "",
                f"- **Category:** {f.get('category', '')}",
                f"- **Framework:** {f.get('framework', '') or 'n/a'}",
                f"- **File:** {f.get('file_path', '') or 'n/a'} {f.get('line_hint', '')}",
                "",
                f.get("description", ""),
                "",
                f"**Recommendation:** {f.get('recommendation', '')}",
                "",
            ])

    if decisions:
        lines.extend(["## Decisions", ""])
        for d in decisions:
            lines.extend([
                f"### {d.get('trigger', '')} → **{d.get('decision', '')}**",
                "",
                f"_{d.get('created_at', '')}_",
                "",
                d.get("reasoning", ""),
                "",
            ])

    if reviews:
        lines.extend(["## Review Log", ""])
        for r in reviews:
            lines.extend([
                f"- **{r.get('trigger', '')}** — verdict `{r.get('verdict', '')}` — {r.get('diff_summary', '')}",
            ])
        lines.append("")

    lines.extend([
        "---",
        f"*Generated by Compliance Review Harness. SQLite retention: `{config.sqlite_path}`*",
    ])
    return "\n".join(lines)


def _render_daily_markdown(config: HarnessConfig, data: dict, date_str: str) -> str:
    sessions = data.get("sessions", [])
    findings = data.get("findings", [])
    decisions = data.get("decisions", [])

    severity_counts = {s: 0 for s in SEVERITY_ORDER}
    for f in findings:
        severity_counts[f.get("severity", "low")] = severity_counts.get(f.get("severity", "low"), 0) + 1

    lines = [
        f"# Daily Compliance Report — {date_str}",
        "",
        f"**Project:** {config.project_name}",
        "",
        "## Overview",
        "",
        f"- Sessions: {len(sessions)}",
        f"- Total decisions: {len(decisions)}",
        f"- Total findings: {len(findings)}",
        "",
        "## Findings by Severity",
        "",
    ]
    for sev in ("critical", "high", "medium", "low"):
        lines.append(f"- **{sev}:** {severity_counts.get(sev, 0)}")
    lines.append("")

    if findings:
        lines.extend(["## All Findings", ""])
        for f in sorted(findings, key=lambda x: SEVERITY_ORDER.get(x["severity"], 0), reverse=True):
            lines.append(
                f"- **[{f['severity'].upper()}]** {f['title']} — {f.get('file_path', '') or 'general'}"
            )
        lines.append("")

    lines.extend([
        "---",
        f"*SQLite archive: `{config.sqlite_path}`*",
    ])
    return "\n".join(lines)
